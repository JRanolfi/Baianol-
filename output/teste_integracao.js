var numero = 10;
function dobrar(valor) {
    return (valor * 2);
}
var resultado = dobrar(numero);
if ((resultado > 15)) {
    console.log("Resultado maior que 15");
} else {
    console.log("Resultado menor ou igual a 15");
}
